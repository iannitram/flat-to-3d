ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = "<!-- generated by tools/session/session.py render sessions/<name>.toml; edit the TOML -->"
PLACEHOLDER = re.compile(r"(?<!\{)\{([^{}]+)\}(?!\})")
PRIVATE = re.compile(r"/home/[^/\s{]+")


def load(path):
    with open(path, "rb") as f: return tomllib.load(f)


def _walk_strings(obj):
    if isinstance(obj, str): yield obj
    elif isinstance(obj, dict):
        for v in obj.values(): yield from _walk_strings(v)
    elif isinstance(obj, list):
        for v in obj: yield from _walk_strings(v)


def validate(doc, path):
    errors = []
    name = doc.get("name")
    stem = pathlib.Path(path).stem

    def err(field, msg):
        errors.append(f"{path}: {field}: {msg}")

    if name != stem:
        err("name", "must match filename stem")
    if doc.get("schema") != 1:
        err("schema", "must be 1")
    if doc.get("q") not in {f"Q{i}" for i in range(17)}:
        err("q", "missing or unknown q")
    if not isinstance(doc.get("issues"), list) or any(
        not isinstance(x, int) for x in doc.get("issues", [])
    ):
        err("issues", "must be integer list")
    if any(x not in doc.get("issues", []) for x in doc.get("evidence_only", [])):
        err("evidence_only", "must be subset of issues")
    if doc.get("evidence_only") and not (doc.get("vars") or {}).get("appid"):
        err("vars.appid", "required for evidence_only")
    if any(d not in {"z13", "quest2", "build-box", "ci"} for d in doc.get("device", [])):
        err("device", "unknown device")

    ids = set()
    answer_ids = set()
    allowed = {"repo", "home", "state", "data", "re_home", "build_box"}
    allowed.update(doc.get("vars", {}))
    for i, step in enumerate(doc.get("step", [])):
        field = f"step[{i}]"
        step_id = step.get("id", "")
        if not re.fullmatch(r"[a-z0-9-]+", step_id):
            err(field + ".id", "invalid id")
        if step_id in ids:
            err(field + ".id", "duplicate id")
        ids.add(step_id)

        kind = step.get("kind")
        who = step.get("who")
        if kind not in {"cmd", "ask", "check", "measure"}:
            err(field + ".kind", "unknown kind")
        if who not in {"you", "script"}:
            err(field + ".who", "must be you or script")
        if step.get("section", "each-run") not in {"setup", "each-run", "check"}:
            err(field + ".section", "unknown section")
        if kind == "cmd" and not isinstance(step.get("run"), list):
            err(field + ".run", "cmd needs run")

        argv = step.get("run", [])
        if not isinstance(argv, list) or any(not isinstance(arg, str) for arg in argv):
            err(field + ".run", "argv must be a list of strings")
            argv = []
        for arg_index, arg in enumerate(argv):
            if PRIVATE.search(arg):
                err(field + ".run", "literal home path is private")
            if arg == "sudo":
                err(field + ".run", "sudo is forbidden")
            if re.search(r"[*?]", arg):
                prior = " ".join(argv[:arg_index])
                if not re.search(r"-name|-iname|-path", prior):
                    err(field + ".run", "glob in argv (fix: use find … -name)")

        content = {key: value for key, value in step.items() if key not in {"done_when", "trouble"}}
        for text in _walk_strings(content):
            for match in PLACEHOLDER.finditer(text):
                key = match.group(1)
                if key.startswith("ans:"):
                    answer_id = key[4:]
                    if answer_id not in answer_ids:
                        err(field, f"{{{key}}} must refer to an earlier answer")
                elif key not in allowed:
                    err(field, "unknown placeholder {" + key + "}")

        if kind in {"ask", "check", "measure"} or (kind == "cmd" and who == "you"):
            answer_ids.add(step_id)
    return errors


def _values(doc):
    home = str(pathlib.Path.home())
    state_home = os.environ.get("XDG_STATE_HOME", str(pathlib.Path(home) / ".local/state"))
    data_home = os.environ.get("XDG_DATA_HOME", str(pathlib.Path(home) / ".local/share"))
    return {
        "repo": str(ROOT),
        "home": home,
        "state": state_home + "/flat3d",
        "data": data_home,
        "re_home": os.environ.get(
            "FLAT3D_RE_HOME", str(pathlib.Path(home) / ".local/share/flat-to-3d")
        ),
        "build_box": os.environ.get("FLAT3D_BUILD_BOX", "craft-build"),
        **doc.get("vars", {}),
    }


def _fill(value, vals, answers=None, render=False):
    left_brace = "\x00FLAT3D_LEFT_BRACE\x00"
    right_brace = "\x00FLAT3D_RIGHT_BRACE\x00"
    escaped = value.replace("{{", left_brace).replace("}}", right_brace)

    def substitute(match):
        key = match.group(1)
        if key.startswith("ans:"):
            if render:
                return match.group(0)
            return str((answers or {}).get(key[4:], match.group(0)))
        return str(vals.get(key, match.group(0)))

    filled = PLACEHOLDER.sub(substitute, escaped)
    return filled.replace(left_brace, "{").replace(right_brace, "}")


def _relative(text, repo):
    return text.replace(repo + os.sep, "").replace(repo, ".")


def render(doc):
    vals={k:v for k,v in _values(doc).items() if k in {"repo", *doc.get("vars",{}).keys()}}
    lines=[HEADER,"", "Placeholders left in braces are filled when the session runs: {home}, {state}, {data}, {re_home}, {build_box}.","",f"# {doc.get('title',doc['name'])}","",f"**Done when:** {doc.get('done_when','')}",""]
    sections=(("setup","One-time setup"),("each-run","Each run, in this order"),("check","What to check (pass = done)"))
    for key,title in sections:
        steps=[s for s in doc.get("step",[]) if s.get("section","each-run")==key]
        if not steps: continue
        lines += [f"## {title}",""]
        for s in steps:
            role="You" if s.get("who")=="you" or s.get("kind") in {"ask","check","measure"} else "Script"
            txt=_relative(_fill(s.get("text",s["id"]),vals,render=True),vals["repo"])
            if s["kind"]=="cmd":
                argv=[_relative(_fill(str(x),vals,render=True),vals["repo"]) for x in s.get("run",[])]
                lines += [f"**{role}:** {txt}","", "```sh", shlex.join(argv), "```",""]
            elif s["kind"]=="check": lines += [f"- [ ] {txt}",""]
            else: lines += [f"**{role}:** {txt}",""]
    troubles=doc.get("trouble",[])
    if troubles:
        lines += ["## If it fails","", "| Symptom | Cause |", "|---|---|"]
        lines += [f"| {t.get('symptom','')} | {t.get('cause','')} |" for t in troubles]
        lines.append("")
    return "\n".join(lines).rstrip()+"\n"


def _json_value(output, pointer):
    obj=json.loads(output.strip().splitlines()[-1]); cur=obj
    for part in pointer.strip("/").split("/") if pointer else []:
        part=part.replace("~1","/").replace("~0","~")
        cur=cur[int(part)] if isinstance(cur,list) else cur[part]
    return cur


def _git_info():
    try:
        commit=subprocess.check_output(["git","-C",str(ROOT),"rev-parse","HEAD"],stderr=subprocess.DEVNULL,text=True).strip()
        dirty=bool(subprocess.check_output(["git","-C",str(ROOT),"status","--porcelain"],stderr=subprocess.DEVNULL,text=True).strip())
        return commit,dirty
    except Exception: return None,None


def _capture_tail(output_file, max_bytes=8192):
    output_file.flush()
    output_file.seek(0, os.SEEK_END)
    end = output_file.tell()
    output_file.seek(max(0, end - max_bytes))
    return "\n".join(output_file.read().splitlines()[-20:])


def _stop_background(process):
    if process.poll() is None:
        try:
            if os.name == "nt":
                process.terminate()
            else:
                os.killpg(process.pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            try:
                if os.name == "nt":
                    process.kill()
                else:
                    os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            process.wait()

    if os.name != "nt":
        try:
            os.killpg(process.pid, 0)
        except ProcessLookupError:
            pass
        else:
            os.killpg(process.pid, signal.SIGKILL)


def _wait_for_background_startup():
    time.sleep(2)


def run(doc, answers, state_dir, now):
    vals = _values(doc)
    scripted = answers is not None
    supplied_answers = answers or {}
    answers_seen = {}
    steps = []
    verdict = "PASS"
    running = []

    try:
        for step in doc.get("step", []):
            text = _fill(step.get("text", step["id"]), vals, answers_seen)
            print(text, flush=True)
            item = {
                "id": step["id"],
                "kind": step["kind"],
                "who": "script" if step["kind"] == "cmd" and step.get("who") == "script" else "you",
                "status": "ok",
                "answer": None,
                "rc": None,
                "code": None,
                "tail": "",
                "metrics": {},
            }
            output = ""
            error_output = ""

            if step["kind"] == "cmd" and step.get("who") == "script":
                argv = [_fill(str(arg), vals, answers_seen) for arg in step.get("run", [])]
                print(shlex.join(argv), flush=True)
                env = os.environ.copy()
                try:
                    if step.get("background"):
                        capture = tempfile.TemporaryFile(mode="w+t", encoding="utf-8")
                        options = {}
                        if os.name != "nt":
                            options["start_new_session"] = True
                        process = None
                        try:
                            process = subprocess.Popen(
                                argv,
                                cwd=ROOT,
                                stdout=capture,
                                stderr=subprocess.STDOUT,
                                text=True,
                                env=env,
                                **options,
                            )
                            running.append((process, capture, item))
                        except BaseException:
                            if process is not None:
                                _stop_background(process)
                            capture.close()
                            raise
                        _wait_for_background_startup()
                        if process.poll() is None:
                            rc = 0
                            output = "background still running"
                        else:
                            rc = process.returncode
                            output = _capture_tail(capture)
                    else:
                        completed = subprocess.run(
                            argv,
                            cwd=ROOT,
                            capture_output=True,
                            text=True,
                            timeout=step.get("timeout", 120),
                            env=env,
                        )
                        rc = completed.returncode
                        output = completed.stdout
                        error_output = completed.stderr

                    item["rc"] = rc
                    item["tail"] = "\n".join(
                        (output + ("\n" + error_output if error_output else "")).splitlines()[-20:]
                    )
                    good = rc in step.get("ok_rc", [0])
                    expected = step.get("expect")
                    if expected and not re.search(_fill(expected, vals, answers_seen), output, re.M):
                        good = False
                    for pointer, expected_value in step.get("expect_json", {}).items():
                        try:
                            if _json_value(output, pointer) != expected_value:
                                good = False
                        except (IndexError, KeyError, TypeError, ValueError, json.JSONDecodeError):
                            good = False
                    expected_code = step.get("expect_code")
                    if expected_code:
                        try:
                            envelope = json.loads(output.strip().splitlines()[-1])
                            item["code"] = envelope["error"]["code"]
                            good = good and item["code"] == expected_code
                        except (IndexError, KeyError, TypeError, ValueError, json.JSONDecodeError):
                            good = False
                    if not good:
                        item["status"] = "fail"
                except subprocess.TimeoutExpired as exc:
                    item.update(status="fail", rc=124, tail=str(exc))
                except OSError as exc:
                    item.update(status="fail", rc=127, tail=str(exc))

            elif step["kind"] == "measure":
                pattern = _fill(step.get("input", ""), vals, answers_seen)
                files = sorted(
                    glob.glob(pattern),
                    key=lambda filename: os.path.getmtime(filename),
                    reverse=True,
                ) if pattern else []
                target = supplied_answers.get(step["id"])
                if not target and files:
                    target = files[0]
                if not target and not scripted:
                    answer_text = _fill(step.get("text", step["id"]), vals, answers_seen)
                    target = input(f"{answer_text} [path or empty to use newest match]: ").strip() or None
                if target:
                    answers_seen[step["id"]] = target
                    item["answer"] = target
                    tool = ROOT / "tools" / "stereo" / (step["tool"] + ".py")
                    measure_args = [
                        _fill(str(arg), vals, answers_seen)
                        for arg in step.get("args", [])
                    ]
                    argv = [sys.executable, str(tool), str(target), "--json", *measure_args]
                    try:
                        completed = subprocess.run(
                            argv,
                            capture_output=True,
                            text=True,
                            timeout=step.get("timeout", 120),
                        )
                        item["rc"] = completed.returncode
                        item["tail"] = "\n".join(completed.stdout.splitlines()[-20:])
                        if completed.stdout.strip():
                            item["metrics"] = json.loads(completed.stdout.splitlines()[-1])
                        item["status"] = "ok" if completed.returncode == 0 else "fail"
                    except (OSError, subprocess.TimeoutExpired, ValueError, json.JSONDecodeError) as exc:
                        item.update(status="fail", tail=str(exc))
                else:
                    item["status"] = "skip" if step.get("optional") else "fail"

            else:
                if step["kind"] == "cmd":
                    argv = [_fill(str(arg), vals, answers_seen) for arg in step.get("run", [])]
                    print(shlex.join(argv), flush=True)
                if step["id"] in supplied_answers:
                    answer = supplied_answers[step["id"]]
                elif scripted:
                    raise ValueError(
                        f"missing answer for step {step['id']} "
                        f"(fix: add \"{step['id']}\" to <ANSWERS.json>)"
                    )
                else:
                    answer = input(f"{text} [y/n/s or value]: ").strip()

                answers_seen[step["id"]] = answer
                item["answer"] = answer
                if step["kind"] == "check":
                    item["status"] = "ok" if answer == "y" else "skip" if answer == "s" else "fail"
                elif step["kind"] == "cmd":
                    item["status"] = "ok" if answer == "y" else "skip" if answer == "s" else "fail"

            if item["status"] == "fail" and not step.get("optional"):
                verdict = "FAIL"
            elif item["status"] == "skip" and not step.get("optional") and verdict != "FAIL":
                verdict = "INCOMPLETE"
            steps.append(item)
    finally:
        for process, capture, item in running:
            try:
                _stop_background(process)
                item["tail"] = _capture_tail(capture)
            finally:
                capture.close()

    commit, dirty = _git_info()
    os_name = ""
    try:
        for line in pathlib.Path("/etc/os-release").read_text().splitlines():
            if line.startswith("PRETTY_NAME="):
                os_name = line.split("=", 1)[1].strip('"')
                break
    except OSError:
        pass

    return {
        "schema": 1,
        "session": doc["name"],
        "q": doc.get("q"),
        "issues": doc.get("issues", []),
        "evidence_only": doc.get("evidence_only", []),
        "vars": doc.get("vars", {}),
        "done_when": doc.get("done_when", ""),
        "started": now,
        "ended": int(time.time()),
        "commit": commit,
        "dirty": dirty,
        "os": os_name,
        "verdict": verdict,
        "steps": steps,
    }


def to_markdown(result):
    refs=", ".join(f"#{n}" for n in result.get("issues",[])) or "none"
    lines=[f"# Session: {result['session']}","",f"**Question:** {result.get('q','')}",f"**Issues:** {refs}",f"**Done when:** {result.get('done_when','')}","",f"Verdict: **{result['verdict']}**", "", "| Step | Status | Evidence |", "|---|---|---|"]
    for s in result["steps"]:
        ev=f"rc={s['rc']}" if s["rc"] is not None else (f"answer={s['answer']}" if s["answer"] is not None else "")
        if s.get("metrics"): ev+=("; " if ev else "")+json.dumps(s["metrics"],sort_keys=True)
        lines.append(f"| {s['id']} | {s['status']} | {ev} |")
    lines += ["", "## Verified", ""]
    lines += [f"- {s['id']}: {s['tail'] or s['status']} ({s['who']})." for s in result["steps"] if s["status"]=="ok"] or ["- None."]
    lines += ["", "## Not verified", ""]
    notv=[s for s in result["steps"] if s["status"]!="ok"]
    lines += [f"- {s['id']}: {s['status']}." for s in notv] or ["- None."]
    for issue in result.get("evidence_only",[]): lines += ["",f"Evidence for #{issue}. This does not close it: #{issue} closes with the works-now recipe PR (`recipes/{result.get('vars',{}).get('appid','<appid>')}-*.recipe`)."]
    return "\n".join(lines)+"\n"


def pending(docs,state_dir):
    passed=set()
    for p in pathlib.Path(state_dir).glob("*.json"):
        try:
            obj=json.loads(p.read_text())
            if obj.get("verdict")=="PASS": passed.add(obj.get("session"))
        except Exception: pass
    out=[]
    for d in docs:
        if d["name"] in passed: continue
        out.append({"name":d["name"],"q":d.get("q"),"ready":all(x in passed for x in d.get("after",[]))})
    return sorted(out,key=lambda x:(int(x["q"][1:]) if x["q"] else 99,x["name"]))


def main(argv=None):
    p=argparse.ArgumentParser();sub=p.add_subparsers(dest="cmd",required=True)
    c=sub.add_parser("check");c.add_argument("files",nargs="*")
    r=sub.add_parser("render");r.add_argument("file");r.add_argument("--out")
    u=sub.add_parser("run");u.add_argument("file");u.add_argument("--script");u.add_argument("--state-dir");u.add_argument("--now",type=int);u.add_argument("--dry-run",action="store_true")
    pn=sub.add_parser("pending");pn.add_argument("--state-dir")
    a=p.parse_args(argv)
    if a.cmd=="check":
        files=[pathlib.Path(x) for x in a.files] or sorted((ROOT/"sessions").glob("*.toml")); allerr=[];names=set();docs=[]
        for f in files:
            try:
                d=load(f);docs.append(d);allerr+=validate(d,str(f))
                if d.get("name") in names: allerr.append(f"{f}: name: duplicate id")
                names.add(d.get("name"))
            except Exception as e: allerr.append(f"{f}: {e}")
        known={d.get("name") for d in docs}
        for f,d in zip(files,docs):
            for dep in d.get("after",[]):
                if dep not in known: allerr.append(f"{f}: after: unknown session {dep}")
        print("\n".join(allerr) if allerr else f"checked {len(files)} sessions: ok");return 1 if allerr else 0
    if a.cmd=="render":
        out=render(load(a.file)); pathlib.Path(a.out).write_text(out,encoding="utf-8",newline="\n") if a.out else print(out,end="");return 0
    state=pathlib.Path(a.state_dir or (_values({})["state"]+"/sessions"))
    if a.cmd=="pending":
        docs=[load(f) for f in sorted((ROOT/"sessions").glob("*.toml"))]
        print("\n".join(f"{x['q']} {x['name']} ({'ready' if x['ready'] else 'waiting'})" for x in pending(docs,state)));return 0
    doc=load(a.file)
    if a.dry_run:
        errors=[];vals=_values(doc)
        for s in doc.get("step",[]):
            print(f"[{s['id']}] {_fill(s.get('text',''),vals,render=True)}")
            if s.get("kind")=="cmd" and s.get("who")=="script":
                argv=[_fill(str(x),vals,render=True) for x in s["run"]];print(shlex.join(argv))
                if argv and "/" not in argv[0] and not shutil.which(argv[0]): errors.append(f"{s['id']}: command not found: {argv[0]}")
        if errors: print("\n".join(errors),file=sys.stderr);return 1
        return 0
    try: answers=json.loads(pathlib.Path(a.script).read_text()) if a.script else None;stamp=a.now if a.now is not None else int(time.time());result=run(doc,answers,state,stamp)
    except (OSError,ValueError,json.JSONDecodeError) as e: print(str(e),file=sys.stderr);return 2
    state.mkdir(parents=True,exist_ok=True);stamp=str(a.now if a.now is not None else int(time.time()));(state/f"{doc['name']}-{stamp}.json").write_text(json.dumps(result,indent=2)+"\n",encoding="utf-8");md=to_markdown(result);(state/f"{doc['name']}-{stamp}.md").write_text(md,encoding="utf-8");print(md,end="")
    return {"PASS":0,"FAIL":1,"INCOMPLETE":3}[result["verdict"]]

if __name__=="__main__": raise SystemExit(main())
