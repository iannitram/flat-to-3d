import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = "<!-- generated by tools/session/session.py render sessions/<name>.toml; edit the TOML -->"
PLACEHOLDER = re.compile(r"\{([^{}]+)\}")
PRIVATE = re.compile(r"/home/[^/\s{]+")


def load(path):
    with open(path, "rb") as f: return tomllib.load(f)


def _walk_strings(obj):
    if isinstance(obj, str): yield obj
    elif isinstance(obj, dict):
        for v in obj.values(): yield from _walk_strings(v)
    elif isinstance(obj, list):
        for v in obj: yield from _walk_strings(v)


def validate(doc, path):
    errors=[]; name=doc.get("name"); stem=pathlib.Path(path).stem
    def err(field,msg): errors.append(f"{path}: {field}: {msg}")
    if name!=stem: err("name", "must match filename stem")
    if doc.get("schema")!=1: err("schema", "must be 1")
    if doc.get("q") not in {f"Q{i}" for i in range(17)}: err("q", "missing or unknown q")
    if not isinstance(doc.get("issues"),list) or any(not isinstance(x,int) for x in doc.get("issues",[])): err("issues","must be integer list")
    if any(x not in doc.get("issues",[]) for x in doc.get("evidence_only",[])): err("evidence_only","must be subset of issues")
    if doc.get("evidence_only") and not (doc.get("vars") or {}).get("appid"): err("vars.appid","required for evidence_only")
    if any(d not in {"z13","quest2","build-box","ci"} for d in doc.get("device",[])): err("device","unknown device")
    ids=set()
    allowed={"repo","home","state","data","re_home","build_box"}
    allowed.update(doc.get("vars",{}))
    for i,s in enumerate(doc.get("step",[])):
        field=f"step[{i}]"; sid=s.get("id","")
        if not re.fullmatch(r"[a-z0-9-]+",sid): err(field+".id","invalid id")
        if sid in ids: err(field+".id","duplicate id")
        ids.add(sid)
        kind=s.get("kind")
        if kind not in {"cmd","ask","check","measure"}: err(field+".kind","unknown kind")
        if s.get("who") not in {"you","script"}: err(field+".who","must be you or script")
        if s.get("section","each-run") not in {"setup","each-run","check"}: err(field+".section","unknown section")
        if kind=="cmd" and not isinstance(s.get("run"),list): err(field+".run","cmd needs run")
        for arg in s.get("run",[]):
            if PRIVATE.search(arg): err(field+".run","literal home path is private")
            if "sudo"==arg: err(field+".run","sudo is forbidden")
            if re.search(r"[*?]",arg) and not re.search(r"-name|-iname|-path", " ".join(s.get("run",[])[:s["run"].index(arg)])): err(field+".run","glob in argv (fix: use find … -name)")
        for text in _walk_strings({k:v for k,v in s.items() if k not in {"done_when","trouble"}}):
            for m in PLACEHOLDER.finditer(text):
                key=m.group(1)
                if key.startswith("ans:"): continue
                if key not in allowed: err(field,"unknown placeholder {"+key+"}")
    return errors


def _values(doc):
    home=str(pathlib.Path.home()); state=os.environ.get("XDG_STATE_HOME",str(pathlib.Path(home)/".local/state"))+"/flat3d"
    data=os.environ.get("XDG_DATA_HOME",str(pathlib.Path(home)/".local/share"))
    return {"repo":str(ROOT),"home":home,"state":state,"data":data,"re_home":os.environ.get("FLAT3D_RE_HOME",str(pathlib.Path(home)/".local/share/flat-to-3d")),"build_box":os.environ.get("FLAT3D_BUILD_BOX","craft-build"),**doc.get("vars",{})}


def _fill(value, vals, answers=None, render=False):
    def sub(m):
        k=m.group(1)
        if k.startswith("ans:"): return m.group(0) if render else str((answers or {}).get(k[4:],m.group(0)))
        return str(vals.get(k,m.group(0)))
    return PLACEHOLDER.sub(sub,value)


def render(doc):
    vals={k:v for k,v in _values(doc).items() if k in {"repo", *doc.get("vars",{}).keys()}}
    lines=[HEADER,"", "Placeholders left in braces are filled when the session runs: {home}, {state}, {data}, {re_home}, {build_box}.","",f"# {doc.get('title',doc['name'])}","",f"**Done when:** {doc.get('done_when','')}",""]
    sections=(("setup","One-time setup"),("each-run","Each run, in this order"),("check","What to check (pass = done)"))
    for key,title in sections:
        steps=[s for s in doc.get("step",[]) if s.get("section","each-run")==key]
        if not steps: continue
        lines += [f"## {title}",""]
        for s in steps:
            role="You" if s.get("who")=="you" or s.get("kind") in {"ask","check","measure"} else "Script"
            txt=_fill(s.get("text",s["id"]),vals,render=True).replace(vals["repo"]+os.sep, "")
            if s["kind"]=="cmd":
                argv=[_fill(str(x),vals,render=True).replace(vals["repo"]+os.sep, "") for x in s.get("run",[])]
                lines += [f"**{role}:** {txt}","", "```sh", shlex.join(argv), "```",""]
            elif s["kind"]=="check": lines += [f"- [ ] {txt}",""]
            else: lines += [f"**{role}:** {txt}",""]
    troubles=doc.get("trouble",[])
    if troubles:
        lines += ["## If it fails","", "| Symptom | Cause |", "|---|---|"]
        lines += [f"| {t.get('symptom','')} | {t.get('cause','')} |" for t in troubles]
        lines.append("")
    return "\n".join(lines).rstrip()+"\n"


def _json_value(output, pointer):
    obj=json.loads(output.strip().splitlines()[-1]); cur=obj
    for part in pointer.strip("/").split("/") if pointer else []:
        part=part.replace("~1","/").replace("~0","~")
        cur=cur[int(part)] if isinstance(cur,list) else cur[part]
    return cur


def _git_info():
    try:
        commit=subprocess.check_output(["git","-C",str(ROOT),"rev-parse","HEAD"],stderr=subprocess.DEVNULL,text=True).strip()
        dirty=bool(subprocess.check_output(["git","-C",str(ROOT),"status","--porcelain"],stderr=subprocess.DEVNULL,text=True).strip())
        return commit,dirty
    except Exception: return None,None


def run(doc, answers, state_dir, now):
    vals=_values(doc); scripted=answers is not None; answers=answers or {}; steps=[]; verdict="PASS"; running=[]
    try:
      for s in doc.get("step",[]):
        print(_fill(s.get("text",s["id"]),vals,answers), flush=True)
        item={"id":s["id"],"kind":s["kind"],"who":"script" if s["kind"]=="cmd" and s.get("who")=="script" else "you","status":"ok","answer":None,"rc":None,"code":None,"tail":"","metrics":{}}
        out=""; errout=""
        if s["kind"]=="cmd" and s.get("who")=="script":
            argv=[_fill(str(x),vals,answers) for x in s.get("run",[])]
            print(shlex.join(argv), flush=True)
            env=os.environ.copy()
            try:
                if s.get("background"):
                    proc=subprocess.Popen(argv,cwd=ROOT,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,text=True,env=env,start_new_session=True);time.sleep(2)
                    if proc.poll() is None: running.append(proc); rc=0; out="background still running"
                    else: rc=proc.returncode;out=proc.stdout.read() if proc.stdout else ""
                else:
                    cp=subprocess.run(argv,cwd=ROOT,capture_output=True,text=True,timeout=s.get("timeout",120),env=env);rc=cp.returncode;out=cp.stdout;errout=cp.stderr
                item["rc"]=rc; item["tail"]="\n".join((out+("\n"+errout if errout else "")).splitlines()[-20:])
                good=rc in s.get("ok_rc",[0])
                if s.get("expect") and not re.search(s["expect"],out,re.M): good=False
                if s.get("expect_json"):
                    for ptr,want in s["expect_json"].items():
                        try:
                            if _json_value(out,ptr)!=want: good=False
                        except Exception: good=False
                if s.get("expect_code"):
                    try:
                        obj=json.loads(out.strip().splitlines()[-1]); item["code"]=obj["error"]["code"]; good &= item["code"]==s["expect_code"]
                    except Exception: good=False
                if not good: item["status"]="fail"
            except subprocess.TimeoutExpired as e: item.update(status="fail",rc=124,tail=str(e))
            except OSError as e: item.update(status="fail",rc=127,tail=str(e))
        elif s["kind"]=="measure":
            ans=answers.get(s["id"]); pattern=_fill(s.get("input",""),vals,answers)
            files=sorted(glob.glob(pattern),key=lambda x:os.path.getmtime(x),reverse=True) if pattern else []
            target=ans or (files[0] if files else None)
            if not target and not scripted:
                target=input(f"{_fill(s.get('text',s['id']),vals,answers)} [path or empty to use newest match]: ").strip() or None
            if not target: item["status"]="skip" if s.get("optional") else "fail"
            else:
                tool=ROOT/"tools"/"stereo"/(s["tool"]+".py"); argv=[sys.executable,str(tool),target,"--json"]+list(s.get("args",[]))
                try:
                    cp=subprocess.run(argv,capture_output=True,text=True,timeout=s.get("timeout",120));item["rc"]=cp.returncode;item["tail"]="\n".join(cp.stdout.splitlines()[-20:]);item["metrics"]=json.loads(cp.stdout.splitlines()[-1]) if cp.stdout.strip() else {};item["status"]="ok" if cp.returncode==0 else "fail"
                except Exception as e: item.update(status="fail",tail=str(e))
        else:
            if s["kind"]=="cmd": print(shlex.join([_fill(str(x),vals,answers) for x in s.get("run",[])]),flush=True)
            if s["id"] in answers: answer=answers[s["id"]]
            elif scripted: raise ValueError(f"missing answer for step {s['id']} (fix: add \"{s['id']}\" to <ANSWERS.json>)")
            else:
                answer=input(f"{_fill(s.get('text',s['id']),vals,answers)} [y/n/s or value]: ").strip()
            item["answer"]=answer
            if s["kind"]=="check": item["status"]="ok" if answer=="y" else "skip" if answer=="s" else "fail"
            elif s["kind"]=="cmd": item["status"]="ok" if answer=="y" else "skip" if answer=="s" else "fail"
        if item["status"]=="fail" and not s.get("optional"): verdict="FAIL"
        elif item["status"]=="skip" and not s.get("optional") and verdict!="FAIL": verdict="INCOMPLETE"
        steps.append(item)
    finally:
      for proc in running:
        try: os.killpg(proc.pid,signal.SIGTERM);proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            try: os.killpg(proc.pid,signal.SIGKILL)
            except ProcessLookupError: pass
            proc.wait()
        except Exception:
            try: os.killpg(proc.pid,signal.SIGKILL)
            except ProcessLookupError: pass
            try: proc.wait(timeout=5)
            except Exception: pass
        finally:
            if proc.stdout:
                proc.stdout.close()
    commit,dirty=_git_info(); osname=""
    try:
        for line in pathlib.Path("/etc/os-release").read_text().splitlines():
            if line.startswith("PRETTY_NAME="): osname=line.split("=",1)[1].strip('"');break
    except OSError: pass
    return {"schema":1,"session":doc["name"],"q":doc.get("q"),"issues":doc.get("issues",[]),"evidence_only":doc.get("evidence_only",[]),"vars":doc.get("vars",{}),"done_when":doc.get("done_when",""),"started":now,"ended":int(time.time()),"commit":commit,"dirty":dirty,"os":osname,"verdict":verdict,"steps":steps}


def to_markdown(result):
    refs=", ".join(f"#{n}" for n in result.get("issues",[])) or "none"
    lines=[f"# Session: {result['session']}","",f"**Question:** {result.get('q','')}",f"**Issues:** {refs}",f"**Done when:** {result.get('done_when','')}","",f"Verdict: **{result['verdict']}**", "", "| Step | Status | Evidence |", "|---|---|---|"]
    for s in result["steps"]:
        ev=f"rc={s['rc']}" if s["rc"] is not None else (f"answer={s['answer']}" if s["answer"] is not None else "")
        if s.get("metrics"): ev+=("; " if ev else "")+json.dumps(s["metrics"],sort_keys=True)
        lines.append(f"| {s['id']} | {s['status']} | {ev} |")
    lines += ["", "## Verified", ""]
    lines += [f"- {s['id']}: {s['tail'] or s['status']} ({s['who']})." for s in result["steps"] if s["status"]=="ok"] or ["- None."]
    lines += ["", "## Not verified", ""]
    notv=[s for s in result["steps"] if s["status"]!="ok"]
    lines += [f"- {s['id']}: {s['status']}." for s in notv] or ["- None."]
    for issue in result.get("evidence_only",[]): lines += ["",f"Evidence for #{issue}. This does not close it: #{issue} closes with the works-now recipe PR (`recipes/{result.get('vars',{}).get('appid','<appid>')}-*.recipe`)."]
    return "\n".join(lines)+"\n"


def pending(docs,state_dir):
    passed=set()
    for p in pathlib.Path(state_dir).glob("*.json"):
        try:
            obj=json.loads(p.read_text())
            if obj.get("verdict")=="PASS": passed.add(obj.get("session"))
        except Exception: pass
    out=[]
    for d in docs:
        if d["name"] in passed: continue
        out.append({"name":d["name"],"q":d.get("q"),"ready":all(x in passed for x in d.get("after",[]))})
    return sorted(out,key=lambda x:(int(x["q"][1:]) if x["q"] else 99,x["name"]))


def main(argv=None):
    p=argparse.ArgumentParser();sub=p.add_subparsers(dest="cmd",required=True)
    c=sub.add_parser("check");c.add_argument("files",nargs="*")
    r=sub.add_parser("render");r.add_argument("file");r.add_argument("--out")
    u=sub.add_parser("run");u.add_argument("file");u.add_argument("--script");u.add_argument("--state-dir");u.add_argument("--now",type=int);u.add_argument("--dry-run",action="store_true")
    pn=sub.add_parser("pending");pn.add_argument("--state-dir")
    a=p.parse_args(argv)
    if a.cmd=="check":
        files=[pathlib.Path(x) for x in a.files] or sorted((ROOT/"sessions").glob("*.toml")); allerr=[];names=set();docs=[]
        for f in files:
            try:
                d=load(f);docs.append(d);allerr+=validate(d,str(f))
                if d.get("name") in names: allerr.append(f"{f}: name: duplicate id")
                names.add(d.get("name"))
            except Exception as e: allerr.append(f"{f}: {e}")
        known={d.get("name") for d in docs}
        for f,d in zip(files,docs):
            for dep in d.get("after",[]):
                if dep not in known: allerr.append(f"{f}: after: unknown session {dep}")
        print("\n".join(allerr) if allerr else f"checked {len(files)} sessions: ok");return 1 if allerr else 0
    if a.cmd=="render":
        out=render(load(a.file)); pathlib.Path(a.out).write_text(out,encoding="utf-8",newline="\n") if a.out else print(out,end="");return 0
    state=pathlib.Path(a.state_dir or (_values({})["state"]+"/sessions"))
    if a.cmd=="pending":
        docs=[load(f) for f in sorted((ROOT/"sessions").glob("*.toml"))]
        print("\n".join(f"{x['q']} {x['name']} ({'ready' if x['ready'] else 'waiting'})" for x in pending(docs,state)));return 0
    doc=load(a.file)
    if a.dry_run:
        errors=[];vals=_values(doc)
        for s in doc.get("step",[]):
            print(f"[{s['id']}] {_fill(s.get('text',''),vals,render=True)}")
            if s.get("kind")=="cmd" and s.get("who")=="script":
                argv=[_fill(str(x),vals,render=True) for x in s["run"]];print(shlex.join(argv))
                if argv and "/" not in argv[0] and not shutil.which(argv[0]): errors.append(f"{s['id']}: command not found: {argv[0]}")
        if errors: print("\n".join(errors),file=sys.stderr);return 1
        return 0
    try: answers=json.loads(pathlib.Path(a.script).read_text()) if a.script else None;stamp=a.now if a.now is not None else int(time.time());result=run(doc,answers,state,stamp)
    except (OSError,ValueError,json.JSONDecodeError) as e: print(str(e),file=sys.stderr);return 2
    state.mkdir(parents=True,exist_ok=True);stamp=str(a.now if a.now is not None else int(time.time()));(state/f"{doc['name']}-{stamp}.json").write_text(json.dumps(result,indent=2)+"\n",encoding="utf-8");md=to_markdown(result);(state/f"{doc['name']}-{stamp}.md").write_text(md,encoding="utf-8");print(md,end="")
    return {"PASS":0,"FAIL":1,"INCOMPLETE":3}[result["verdict"]]

if __name__=="__main__": raise SystemExit(main())
